const fs = require('fs');
const path = require('path');

const CONTRACTS = [
  { 
    name: 'BoardGovernance', 
    jsonName: 'BoardGovernance.sol/BoardGovernance.json', 
    tsFile: 'board-governance.ts', 
    exportName: 'BoardGovernance' 
  },
  { 
    name: 'EquityToken', 
    jsonName: 'EquityToken.sol/EquityToken.json', 
    tsFile: 'equity-token.ts', 
    exportName: 'EquityToken' 
  },
  { 
    name: 'FinanceManager', 
    jsonName: 'FinanceManager.sol/FinanceManager.json', 
    tsFile: 'finance-manager.ts', 
    exportName: 'FinanceManager' 
  },
  { 
    name: 'Marketplace', 
    jsonName: 'Marketplace.sol/Marketplace.json', 
    tsFile: 'marketplace.ts', 
    exportName: 'Marketplace' 
  }
];

const ARTIFACTS_DIR = path.join(__dirname, '../artifacts/contracts');
const OUTPUT_DIR = path.join(__dirname, '../../ptt-web/src/app/core/constants/contracts');

for (const c of CONTRACTS) {
  const jsonPath = path.join(ARTIFACTS_DIR, c.jsonName);
  if (!fs.existsSync(jsonPath)) {
    console.warn(`[SKIP] Không tìm thấy artifact cho ${c.name} tại ${jsonPath}`);
    continue;
  }

  const artifact = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  const abi = JSON.stringify(artifact.abi, null, 2);
  const bytecode = artifact.bytecode;

  const tsContent = `// Auto-generated by scratch_sync_constants.js. Do not edit directly.
export const ${c.exportName} = {
  abi: ${abi},
  bytecode: "${bytecode}"
};
`;

  const tsPath = path.join(OUTPUT_DIR, c.tsFile);
  fs.writeFileSync(tsPath, tsContent, 'utf8');
  console.log(`[OK] Đã đồng bộ ${c.name} -> ${c.tsFile}`);
}

console.log('Hoàn tất đồng bộ tất cả contracts!');
