const fs = require('fs');
const path = require('path');

const contractJsonPath = path.join(__dirname, '../artifacts/contracts/EquityToken.sol/EquityToken.json');
const flatPath = path.join(__dirname, '../flattened/EquityToken.flat.sol');
const tsPath = path.join(__dirname, '../../ptt-web/src/app/core/constants/contracts/equity-token.ts');

if (!fs.existsSync(contractJsonPath)) {
  console.error("Not found artifact JSON!");
  process.exit(1);
}

const artifact = JSON.parse(fs.readFileSync(contractJsonPath, 'utf8'));
const abi = JSON.stringify(artifact.abi, null, 2);
const bytecode = artifact.bytecode;

let sourceCode = '';
if (fs.existsSync(flatPath)) {
  sourceCode = fs.readFileSync(flatPath, 'utf8');
} else {
  console.warn("Flat file not found, sourceCode will be empty");
}

const escaped = sourceCode.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\${/g, '\\${');

const tsContent = `// Auto-generated by scratch_sync_constants.js. Do not edit directly.
export const EquityToken = {
  abi: ${abi},
  bytecode: "${bytecode}",
  sourceCode: \`${escaped}\`
};
`;

fs.writeFileSync(tsPath, tsContent, 'utf8');
console.log("Sync constants successfully!");
